import argparse
import ctypes
import json
import os
import sys


REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BUILD_DLL_PATH = os.path.join(
    REPO_ROOT, "SKSE_Source", "build", "release", "Release", "BodyLanguage.dll"
)
BUNDLED_DLL_PATH = os.path.join(os.path.dirname(__file__), "bin", "BodyLanguage.dll")


def _resolve_default_dll_path() -> str:
    """
    Prefers the freshest available BodyLanguage.dll between the local CMake build folder
    (when developing locally) and `utility_scripts/bin/BodyLanguage.dll` (bundled in git
    so anyone who pulls the repo can run the Python scripts without building C++).
    """
    candidates = [p for p in (BUILD_DLL_PATH, BUNDLED_DLL_PATH) if os.path.exists(p)]
    if not candidates:
        return BUNDLED_DLL_PATH
    return max(candidates, key=os.path.getmtime)


DEFAULT_DLL_PATH = _resolve_default_dll_path()
BASE_3BA_NIF = os.path.join(
    os.path.dirname(__file__), "body samples", "3ba", "cbbe vanilla", "femalebody_1.nif"
)
BASE_HIMBO_NIF = os.path.join(
    os.path.dirname(__file__), "body samples", "himbo", "zero", "malebody_1.nif"
)
GROUND_TRUTH_JSON = os.path.join(os.path.dirname(__file__), "body_samples_ground_truth.json")


class BodyLanguageCppBridge:
    """
    Loads the compiled BodyLanguage.dll directly via ctypes and invokes the exported
    C++ function `BodyLanguage_EvaluateNifForTest` (which runs NifTriParser.cpp ->
    NifRingIndexer.cpp -> ActorBodyEvaluator.cpp -> PhysiqueClassifier.cpp).
    Zero C++ logic is duplicated in Python.
    """

    def __init__(self, dll_path: str):
        if not os.path.exists(dll_path):
            raise FileNotFoundError(
                f"Compiled C++ plugin not found at '{dll_path}'. Please build the C++ project first."
            )
        self.dll = ctypes.CDLL(dll_path)
        if not hasattr(self.dll, "BodyLanguage_EvaluateNifForTest"):
            raise RuntimeError(
                f"'{dll_path}' does not export 'BodyLanguage_EvaluateNifForTest' yet. "
                "Please rebuild the C++ project in Visual Studio / CMake so the new export in plugin.cpp is compiled into BodyLanguage.dll."
            )
        self._fn = self.dll.BodyLanguage_EvaluateNifForTest
        self._fn.argtypes = [
            ctypes.c_char_p,  # dataRootPath
            ctypes.c_char_p,  # nifFilePath
            ctypes.c_char_p,  # baseTemplateNifPath ("" for direct NIF indexing, or path for OBody template mode)
            ctypes.c_int,     # isFemale
            ctypes.c_int,     # isNaked
            ctypes.c_float,   # texToneScore
            ctypes.c_char_p,  # outJsonBuffer
            ctypes.c_int,     # outJsonBufferSize
        ]
        self._fn.restype = ctypes.c_int
        self._buf_size = 65536
        self._buf = ctypes.create_string_buffer(self._buf_size)

    def evaluate_nif(
        self,
        data_root: str,
        nif_path: str,
        base_template_nif: str = "",
        is_female: bool = True,
        is_naked: bool = True,
        tex_tone_score: float = 0.25,
    ) -> dict:
        rc = self._fn(
            data_root.encode("utf-8"),
            nif_path.encode("utf-8"),
            base_template_nif.encode("utf-8") if base_template_nif else b"",
            1 if is_female else 0,
            1 if is_naked else 0,
            float(tex_tone_score),
            self._buf,
            self._buf_size,
        )
        if rc < 0:
            raise RuntimeError(f"BodyLanguage_EvaluateNifForTest failed with code {rc} on '{nif_path}'")
        raw_json = self._buf.value.decode("utf-8")
        return json.loads(raw_json)


def main():
    parser = argparse.ArgumentParser(
        description="Runs compiled C++ BodyLanguage.dll against sample NIFs and compares with Ground Truth."
    )
    parser.add_argument(
        "--dll",
        default=DEFAULT_DLL_PATH,
        help="Path to compiled BodyLanguage.dll",
    )
    parser.add_argument(
        "--ground-truth",
        default=GROUND_TRUTH_JSON,
        help="Path to body_samples_ground_truth.json generated by analyze_body_samples.py",
    )
    parser.add_argument(
        "--preset",
        default="",
        help="Optional substring filter for preset name",
    )
    parser.add_argument(
        "--tex-tone",
        type=float,
        default=0.25,
        help="Normal map texture tone score passed to C++ classifier (default: 0.25)",
    )
    args = parser.parse_args()

    if not os.path.exists(args.ground_truth):
        print(
            f"[ERROR] Ground truth file '{args.ground_truth}' not found.\n"
            f"Run: python utility_scripts/analyze_body_samples.py"
        )
        sys.exit(1)

    with open(args.ground_truth, "r", encoding="utf-8") as f:
        gt_data = json.load(f)

    try:
        bridge = BodyLanguageCppBridge(args.dll)
    except Exception as e:
        print(f"[ERROR] {e}")
        sys.exit(1)

    rows = []
    for key, gt in gt_data["samples"].items():
        if args.preset and args.preset.lower() not in key.lower():
            continue

        nif_path = os.path.join(REPO_ROOT, gt["nif_path"])
        is_fem = gt.get("is_female", "female" in os.path.basename(nif_path).lower())
        base_tpl = BASE_3BA_NIF if is_fem else (BASE_HIMBO_NIF if os.path.exists(BASE_HIMBO_NIF) else "")
        cpp_dir = bridge.evaluate_nif(
            REPO_ROOT, nif_path, base_template_nif="", is_female=is_fem, is_naked=True, tex_tone_score=args.tex_tone
        )
        cpp_obd = bridge.evaluate_nif(
            REPO_ROOT,
            nif_path,
            base_template_nif=base_tpl,
            is_female=is_fem,
            is_naked=True,
            tex_tone_score=args.tex_tone,
        )
        rows.append((key, gt, cpp_dir, cpp_obd))

    sys.stdout.flush()
    print("\n" + "=" * 170)
    print(
        f"{'Preset':26s} | {'Src':4s} | {'Chest\"':6s} {'Under\"':6s} {'Waist\"':6s} {'Belly\"':6s} {'Hips\"':6s} {'Thigh\"':6s} | "
        f"{'BMI':4s} {'BustC':5s} {'WHR':4s} {'BDrop':6s} {'HipsR':5s} | "
        f"{'Frame':7s} {'Breasts':10s} {'Waist':8s} {'Belly':6s} {'Hips/Butt':14s} {'Legs':8s} {'Cond':9s}"
    )
    print("=" * 170)

    for key, gt, cpp_dir, cpp_obd in rows:
        gt_m = gt["measurements_in"]
        gt_r = gt["ratios"]

        print(
            f"{key:26s} | {'GT':4s} | "
            f"{gt_m['chest']:6.1f} {gt_m['underbust']:6.1f} {gt_m['waist']:6.1f} "
            f"{gt_m['belly']:6.1f} {gt_m['hips']:6.1f} {gt_m['thigh']:6.1f} | "
            f"{gt_r['bmi']:4.2f} {gt_r['bustCup']:5.2f} {gt_r['whr']:4.2f} "
            f"{gt_r['bellyDrop']:+6.3f} {gt_r['hips']:5.2f} | "
            f"(Exact 3D Triangle-Slice Ground Truth)"
        )

        for label, res in (("DIR", cpp_dir), ("RTM", cpp_obd)):
            m_in = res["measurements_in"]
            r = res["ratios"]
            kw = res["keywords"]
            k_frame = kw.get("frame", kw.get("shoulder_breadth", ""))
            k_chest = kw.get("breasts_volume", kw.get("chest", ""))
            k_waist = kw.get("waist", kw.get("stature_frame", ""))
            k_belly = kw.get("belly", kw.get("midsection", ""))
            k_hips = kw.get("butt_hips", kw.get("glutes", ""))
            k_legs = kw.get("legs", "")
            k_cond = kw.get("physique_condition", "")
            print(
                f"{'':26s} | {label:4s} | "
                f"{m_in['chest']:6.1f} {m_in['underbust']:6.1f} {m_in['waist']:6.1f} "
                f"{m_in['belly']:6.1f} {m_in['hips']:6.1f} {m_in['thigh']:6.1f} | "
                f"{r['bmi']:4.2f} {r['bustCup']:5.2f} {r['whr']:4.2f} "
                f"{r['bellyDrop']:+6.3f} {r['hips']:5.2f} | "
                f"{k_frame:7s} {k_chest:10s} {k_waist:8s} "
                f"{k_belly:12s} {k_hips:14s} {k_legs:8s} {k_cond:9s}"
            )
        print(f"{'':26s}   -> C++ Short Desc (RTM): \"{cpp_obd['shortDesc']}\"")
        print("-" * 170)


if __name__ == "__main__":
    main()
